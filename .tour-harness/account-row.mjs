// verify:account-row — PROFILE HAS AN ACCOUNT ROW, AND IT TELLS THE TRUTH ABOUT WHICH OF THREE STATES IT IS IN.
//
// His request 20 Nov 2026, "Build the account row": the email prompt could be snoozed for a week and there was
// nowhere else to save an email, so somebody worried about losing their progress had no way to act on it. The page
// is the Profile test page with the real ProfileScreen; its fake sign-in holds the user, and a save writes into it
// so the row is re-read from what the save did. ?confirm=1 is a project that holds the address until the link in
// its email is tapped, which must never be called "saved".
import { startDriver } from './driver-kit.mjs'

const d = await startDriver({ port: 9976, page: 'profile.html', name: 'account-row', timeoutMs: 200_000 })
const { ev, check, wait, go, until, shoot, finish } = d

const ROW = 'Email & sign-in'
const rowValue = () => ev(`(() => { const r = document.querySelector('[data-profile-row=${JSON.stringify(ROW)}]'); return r ? r.textContent : null })()`)
const state = () => ev(`document.querySelector('[data-account-state]')?.getAttribute('data-account-state') ?? null`)
const sheetText = () => ev(`document.querySelector('[data-profile-sheet="account"]')?.textContent ?? ''`)
const open = async query => {
  await go(query)
  await until(() => ev(`!!document.querySelector('[data-testid="open-profile"]')`), v => v === true, 120)
  await ev(`document.querySelector('[data-testid="open-profile"]')?.click()`)
  await until(rowValue, v => v != null && !v.includes('…'), 60)
  await wait(300)
}
const openSheet = async () => {
  await ev(`document.querySelector('[data-profile-row=${JSON.stringify(ROW)}]')?.click()`)
  await until(() => ev(`!!document.querySelector('[data-profile-sheet="account"]')`), v => v === true, 30)
  await wait(300)
}
const type = (id, text) => ev(`(() => { const el = document.getElementById(${JSON.stringify(id)}); if (!el) return false
  const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; set.call(el, ${JSON.stringify(text)})
  el.dispatchEvent(new Event('input', { bubbles: true })); return true })()`)
const save = async () => { await ev(`document.querySelector('[data-account-save]')?.click()`); await wait(900) }
const inView = () => ev(`(() => { const r = document.querySelector('[data-profile-row=${JSON.stringify(ROW)}]')?.getBoundingClientRect(); return !!r && r.top >= 0 && r.bottom <= innerHeight })()`)

console.log('\n  1. NOT SAVED: THE ROW SAYS SO AND THE SHEET SAVES IT')
await open('&account=none')
check('1a. the row is on Profile and says "Not saved yet"', /Not saved yet/.test((await rowValue()) ?? ''), await rowValue())
check('1b. ...without scrolling: it is the first row', (await inView()) === true)
await shoot('account-row-1-row')
await openSheet()
check('1c. the sheet explains what is at stake and holds the form', (await state()) === 'not-saved' && /only on this phone/.test(await sheetText()), await sheetText())
check('1d. ...and its secondary button is Cancel, not the prompt\'s week-long "Not now"', /Cancel/.test(await sheetText()) && !/Not now/.test(await sheetText()))
await type('account-email', 'nope')
await type('account-password', 'longenough')
await save()
check('1e. a bad address is refused in words, and nothing is written', /doesn't look like an email/.test(await sheetText()) && (await ev(`(window.__authWrites ?? []).length`)) === 0)
await type('account-email', 'sam@example.com')
await save()
check('1f. a good one is written to the account', (await ev(`JSON.stringify(window.__authWrites ?? [])`)).includes('sam@example.com'))
check('1g. the sheet says it is tied to that email and how to get back in', (await state()) === 'just-saved' && /tied to sam@example.com/.test(await sheetText()) && /Already have an account\? Sign in/.test(await sheetText()), await sheetText())
await shoot('account-row-1-saved')
await ev(`document.querySelector('[data-profile-back]')?.click()`)
await until(() => ev(`!!document.querySelector('[data-profile-sheet]')`), v => v === false, 20)
check('1h. back on Profile, the row now names the email', /sam@example\.com/.test((await rowValue()) ?? ''), await rowValue())

console.log('\n  2. A PROJECT THAT ASKS FOR THE LINK TO BE TAPPED: NEVER CALLED SAVED')
await open('&account=none&confirm=1')
await openSheet()
await type('account-email', 'sam@example.com')
await type('account-password', 'longenough')
await save()
check('2a. after the save the sheet says to tap the link, and that it is NOT saved yet', (await state()) === 'just-saved' && /Tap it to finish/.test(await sheetText()) && /isn't saved/.test(await sheetText()) && !/tied to/.test(await sheetText()), await sheetText())
await ev(`document.querySelector('[data-profile-back]')?.click()`)
await wait(500)
check('2b. ...and the row says "Check your email", not the address', /Check your email/.test((await rowValue()) ?? '') && !/sam@example/.test((await rowValue()) ?? ''), await rowValue())

console.log('\n  3. ALREADY SAVED, AND ALREADY WAITING')
await open('&account=saved')
check('3a. a saved account shows its email on the row', /sam@example\.com/.test((await rowValue()) ?? ''), await rowValue())
await openSheet()
check('3b. ...and the sheet says signed in, with no form', (await state()) === 'saved' && /Signed in as/.test(await sheetText()) && !(await ev(`!!document.getElementById('account-email')`)))
await shoot('account-row-3-signed-in')
await open('&account=confirming')
check('3c. an address waiting on its link reads "Check your email"', /Check your email/.test((await rowValue()) ?? ''), await rowValue())
await openSheet()
check('3d. ...and the sheet names it and says it is not saved yet', (await state()) === 'confirming' && /sam@example\.com/.test(await sheetText()) && /isn't saved/.test(await sheetText()))

console.log('\n  4. A USER THE APP CANNOT READ IS NEVER "NOT SAVED"')
await open('')
check('4a. no user read: the row says it could not check', /Couldn.t check/.test((await rowValue()) ?? ''), await rowValue())
await openSheet()
check('4b. ...and offers no form that would write to nothing', (await state()) === 'unknown' && !(await ev(`!!document.getElementById('account-email')`)))

const calls = () => ev(`JSON.parse(sessionStorage.getItem('__fakeAuthCalls') ?? '[]')`)
const clearCalls = () => ev(`sessionStorage.removeItem('__fakeAuthCalls')`)
const click = sel => ev(`(() => { const el = document.querySelector('${sel}'); if (!el) return false; el.click(); return true })()`)
const typeIn = (id, text) => type(id, text)

console.log('\n  5. WAITING ON THE LINK: RESEND AND A DIFFERENT ADDRESS, NEVER THE PASSWORD AGAIN (23 Nov 2026)')
await open('&account=confirming&confirm=1')
await clearCalls()
await openSheet()
check('5a. the waiting sheet has no password box', !(await ev(`!!document.querySelector('[data-profile-sheet="account"] input[type=password]')`)))
check('5b. ...and says to check the spam folder', /spam folder/.test(await sheetText()), await sheetText())
await click('[data-account-resend]')
await until(() => ev(`!!document.querySelector('[data-account-note]')`), v => v === true, 20)
const resent = (await calls()).filter(c => c.name === 'resend')
check('5c. Resend sends the same link again, to the waiting address, and back to the app', resent.length === 1 && resent[0].email === 'sam@example.com' && resent[0].type === 'email_change' && /^http/.test(resent[0].redirect ?? ''), await calls())
check('5d. ...and says it was sent, on screen', /Sent again to sam@example\.com/.test(await sheetText()), await sheetText())
await shoot('account-row-5-resend')
await click('[data-account-change]')
await wait(300)
await typeIn('account-new-email', 'sam2@example.com')
await click('[data-account-change-save]')
await until(() => ev(`document.querySelector('[data-account-note]')?.textContent ?? ''`), v => /sam2@/.test(v), 20)
const changed = (await calls()).filter(c => c.name === 'updateUser')
check('5e. a different address writes the address ALONE: no password is set again', changed.length === 1 && changed[0].email === 'sam2@example.com' && !('password' in changed[0]), changed)
check('5f. ...and the sheet now names the new address', /sam2@example\.com/.test(await sheetText()), await sheetText())

console.log('\n  6. THE WEEKLY PROMPT AND THE FIRST SAVE')
await open('&account=none&confirm=1')
await clearCalls()
await openSheet()
await type('account-email', 'sam@example.com')
await type('account-password', 'longenough')
await save()
const first = (await calls()).filter(c => c.name === 'updateUser')
check('6a. the first save names the app as where the link comes back to', first.length === 1 && /^http/.test(first[0].redirect ?? ''), first)

console.log('\n  7. SIGNED IN: SIGN OUT, ASKED FIRST, NEVER WITH UNSENT SETS')
await open('&account=saved')
await openSheet()
await ev(`localStorage.setItem('fitplan_setlog_pending_v1', JSON.stringify([{ clientId: 'x1' }]))`)
await clearCalls()
await click('[data-account-signout]')
await wait(300)
check('7a. Sign out asks first, and says the plan stays on the account', /stay on your account/.test(await sheetText()) && /sam@example\.com/.test(await sheetText()), await sheetText())
await shoot('account-row-7-signout-ask')
await click('[data-account-signout-yes]')
await wait(800)
check('7b. with a set not yet sent, it refuses in words and signs nothing out', /1 set hasn't reached the server/.test(await sheetText()) && !(await calls()).some(c => c.name === 'signOut'), { text: await sheetText(), calls: await calls() })
await ev(`localStorage.removeItem('fitplan_setlog_pending_v1'); localStorage.setItem('fitplan_profile_id', 'old-person'); localStorage.setItem('sb-test-auth-token', 'kept')`)
await click('[data-account-signout-yes]')
await until(() => ev(`(JSON.parse(sessionStorage.getItem('__fakeAuthCalls') ?? '[]')).some(c => c.name === 'signOut') && localStorage.getItem('fitplan_profile_id') === null`), v => v === true, 40)
await wait(1500)
check('7c. with nothing waiting, it signs out of this phone only', (await calls()).some(c => c.name === 'signOut' && c.scope === 'local'), await calls())
check('7d. ...and the phone forgets the last person’s plan, keeping the sign-in’s own keys', (await ev(`localStorage.getItem('fitplan_profile_id')`)) === null && (await ev(`localStorage.getItem('sb-test-auth-token')`)) === 'kept')
await ev(`localStorage.removeItem('sb-test-auth-token')`)

console.log('\n  8. A PHONE WITH A PLAN BUT NO EMAIL: SIGN IN, AND FORGOT PASSWORD')
await open('&account=none')
await clearCalls()
await openSheet()
await click('[data-account-signin]')
await wait(300)
check('8a. "Already have an account? Sign in" first says this plan stays behind', /leaves it behind/.test(await sheetText()), await sheetText())
await click('[data-account-signin-yes]')
await until(() => ev(`!!document.querySelector('[data-account-signin-screen]')`), v => v === true, 20)
check('8b. ...then the sign-in screen opens over Profile', await ev(`!!document.getElementById('signin-email')`))
await typeIn('signin-email', 'sam@example.com')
await typeIn('signin-password', 'wrong')
await ev(`[...document.querySelectorAll('[data-account-signin-screen] button')].find(b => b.textContent.trim() === 'Sign in')?.click()`)
await wait(900)
const screenText = () => ev(`document.querySelector('[data-account-signin-screen]')?.textContent ?? ''`)
check('8c. a wrong password is said in plain words', /don't match an account/.test(await screenText()), await screenText())
await click('[data-signin-forgot]')
await until(() => ev(`!!document.querySelector('[data-signin-note]')`), v => v === true, 20)
const reset = (await calls()).filter(c => c.name === 'resetPasswordForEmail')
check('8d. Forgot your password? sends a reset link to the typed address, back to the app', reset.length === 1 && reset[0].email === 'sam@example.com' && /^http/.test(reset[0].redirect ?? ''), await calls())
check('8e. ...and says so without saying whether the address has an account', /If sam@example\.com has an account/.test(await screenText()), await screenText())
await shoot('account-row-8-forgot')
await ev(`[...document.querySelectorAll('[data-account-signin-screen] button')].find(b => b.textContent.trim() === 'Cancel')?.click()`)
await wait(300)
check('8f. Cancel closes the sign-in and leaves the plan where it was', !(await ev(`!!document.querySelector('[data-account-signin-screen]')`)) && (await state()) === 'not-saved')

console.log('\n  9. THE PAGE A RESET LINK OPENS')
await go('&newpassword=1')
await until(() => ev(`!!document.getElementById('new-password')`), v => v === true, 120)
await clearCalls()
await typeIn('new-password', 'short')
await click('[data-new-password-save]')
await wait(500)
check('9a. a short password is refused in words and nothing is written', /at least 8 characters/.test(await ev(`document.body.textContent`)) && !(await calls()).some(c => c.name === 'updateUser'))
await shoot('account-row-9-new-password')

await finish('verify:account-row passed: the Account row says which state the account is in, saves an email, resends a link, signs out, signs in and resets a password.')
